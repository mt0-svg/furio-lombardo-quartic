#!/bin/bash
# Writes lean/FurioLombardo/Discharge/SelmerBasis/TowerChecks.lean: one kernel check per identity of the tower data
# (SUnitData.lean) used by GlobalCRT.lean: the power tables of A = alphaDen alpha and B = betaPowDen beta, the roots
# q k (alpha) = 0 and h k (beta) = 0, and the 82 x 2 values Pgen s (alpha), Pgen s (beta).
# Usage: code/selmer-global-bound/tower_checks_gen.sh (from the repository root); LEANOUT=<dir> writes into <dir> instead.
set -eu
cd "$(dirname "$0")/../.."
out=${LEANOUT:-lean/FurioLombardo/Discharge/SelmerBasis}; out=${out%/}/TowerChecks.lean
K=1024
{
cat <<'EOF'
import FurioLombardo.Discharge.SelmerBasis.TowerEval
import FurioLombardo.Discharge.M3a.ConcreteDefs

/-!
# Kernel checks of the tower data (generated by code/selmer-global-bound/tower_checks_gen.sh)

With `A = alphaDen α ∈ L42` and `B = betaPowDen β ∈ N84` (SUnitData.lean), the tables `tabA`, `tabB`
of the coordinates of `A^i`, `B^i` (`i ≤ 5`) are checked step by step (`ck_tabA_i`, `ck_tabB_i`),
`P_1` against `alphaL`, `2 betaN`. Then, one `checkLC` / `checkNC` each (`sumPL`, `sumPN` of
TowerEval.lean):

* `ck_qA_k`, `ck_hB_k`: `q k (α) = 0`, `h k (β) = 0` (`k = 0, 1`);
* `ck_pA_s`, `ck_pB_s`: `Pgen s (α)` and `Pgen s (β)` are `gensL s, 1` (`s < 29`) or
  `1, gensN (s - 29)` (`s ≥ 29`).

Every statement is closed by `decide +kernel`, one identity per declaration.
-/

namespace FurioLombardo.Discharge.SelmerBasis.TowerChecks

open FurioLombardo.M1 FurioLombardo.M1.Kron FurioLombardo.Discharge.M3a FurioLombardo.Discharge.M3a.Bruin
  FurioLombardo.Discharge.SelmerBasis FurioLombardo.Discharge.SelmerBasis.Tower SUnitData

set_option maxRecDepth 100000

/-- The coordinates of `A^i`, `A = alphaDen α`. -/
def tabA : List LC :=
  [ofL alphaPow_0, ofL alphaPow_1, ofL alphaPow_2, ofL alphaPow_3, ofL alphaPow_4, ofL alphaPow_5]

/-- The coordinates of `B^i`, `B = betaPowDen β`. -/
def tabB : List NC :=
  [ofN betaPow_0, ofN betaPow_1, ofN betaPow_2, ofN betaPow_3, ofN betaPow_4, ofN betaPow_5]

/-- `2 betaN` in the coordinates of `mkN` (`betaPowDen = 2 betaDen`). -/
def twoBetaN : NC :=
  ((.mul (.int 2) (.lin (betaN.getD 0 [])), .mul (.int 2) (.lin (betaN.getD 1 []))),
    (.lin (betaN.getD 2 []), .lin (betaN.getD 3 [])))

EOF
echo "theorem ck_tabA_0 : checkLC $K (ofL alphaPow_0) oneLC = true := by decide +kernel"
echo
echo "theorem ck_tabA_1 : checkLC $K (ofL alphaPow_1) (ofL alphaL) = true := by decide +kernel"
echo
for i in 2 3 4 5; do
  echo "theorem ck_tabA_$i : checkLC $K (ofL alphaPow_$i) (mulLC (ofL alphaPow_$((i - 1))) (ofL alphaPow_1)) = true := by"
  echo "  decide +kernel"
  echo
done
echo "theorem ck_tabB_0 : checkNC $K (ofN betaPow_0) oneNC = true := by decide +kernel"
echo
echo "theorem ck_tabB_1 : checkNC $K (ofN betaPow_1) twoBetaN = true := by decide +kernel"
echo
for i in 2 3 4 5; do
  echo "theorem ck_tabB_$i : checkNC $K (ofN betaPow_$i) (mulNC (ofN betaPow_$((i - 1))) (ofN betaPow_1)) = true := by"
  echo "  decide +kernel"
  echo
done
for k in 0 1; do
  echo "theorem ck_qA_$k : checkLC $K (sumPL alphaDen 2 (qL $k) tabA)"
  echo "    (smulLC (.int ((alphaDen ^ 2 * qDenN $k : ℕ) : ℤ)) zeroLC) = true := by decide +kernel"
  echo
  echo "theorem ck_hB_$k : checkNC $K (sumPN betaPowDen 4 (hL $k) tabB)"
  echo "    (smulNC (.int ((betaPowDen ^ 4 * hDenN $k : ℕ) : ℤ)) zeroNC) = true := by decide +kernel"
  echo
done
for s in $(seq 0 81); do
  if [ "$s" -lt 29 ]; then tA="(ofL (gL.getD $s []))"; tB="oneNC"
  else tA="oneLC"; tB="(ofN (gN.getD $((s - 29)) []))"; fi
  echo "theorem ck_pA_$s : checkLC $K (sumPL alphaDen 5 ((pgen.getD $s []).map .lin) tabA)"
  echo "    (smulLC (.int ((alphaDen ^ 5 * pgenDen.getD $s 1 : ℕ) : ℤ)) $tA) = true := by decide +kernel"
  echo
  echo "theorem ck_pB_$s : checkNC $K (sumPN betaPowDen 5 ((pgen.getD $s []).map .lin) tabB)"
  echo "    (smulNC (.int ((betaPowDen ^ 5 * pgenDen.getD $s 1 : ℕ) : ℤ)) $tB) = true := by decide +kernel"
  echo
done
gen_all() { # name, check prefix, kind (L|N), range, index expression, table, den, target
  local nm=$1 ck=$2 kind=$3 n=$4 ix=$5 tab=$6 den=$7 tgt=$8 v=$9
  local sum=sumP$kind chk=check${kind}C smul=smul${kind}C
  echo "theorem $nm : ∀ $v, $v < $n → $chk $K ($sum $den 5 ((pgen.getD ($ix) []).map .lin) $tab)"
  echo "    ($smul (.int (($den ^ 5 * pgenDen.getD ($ix) 1 : ℕ) : ℤ)) $tgt) = true := by"
  echo "  intro $v h$v"
  echo "  interval_cases $v"
  local l="" o=0; [ "$ix" = "$v" ] || o=29
  for t in $(seq 0 $((n - 1))); do l="$l${l:+, }${ck}_$((t + o))"; done
  echo "  exacts [$l]"
  echo
}
gen_all ck_pA_left ck_pA L 29 i tabA alphaDen "(ofL (gL.getD i []))" i
gen_all ck_pA_right ck_pA L 53 "29 + j" tabA alphaDen oneLC j
gen_all ck_pB_left ck_pB N 29 i tabB betaPowDen oneNC i
gen_all ck_pB_right ck_pB N 53 "29 + j" tabB betaPowDen "(ofN (gN.getD j []))" j
echo "theorem pgen_length : ∀ s < 82, (pgen.getD s []).length = 6 := by decide +kernel"
echo
echo "theorem pgenDen_ne_zero : ∀ s < 82, pgenDen.getD s 1 ≠ 0 := by decide +kernel"
echo
echo "end FurioLombardo.Discharge.SelmerBasis.TowerChecks"
} > "$out"
echo "wrote $out"
